"""
生成绿色版里的《使用说明.txt》。

用法：
    python dev/client/build/make_readme.py --out <包目录>
"""
from __future__ import annotations

import argparse
from pathlib import Path

TEXT = """ESP32-S3 遥控器桥接 —— 使用说明
================================================================

一、这是什么
----------------------------------------------------------------
开发板（ESP32-S3）插在电脑上，它是一个「蓝牙遥控器接收器」：
遥控器 -> 蓝牙 -> 开发板 -> USB -> 电脑。

开发板同时扮演两个角色：
  · USB 键盘   —— 把遥控器的按键变成电脑上的按键
  · USB 串口   —— 和本软件通信（配对、学习、语音数据）

所以你也可以把开发板直接插到**另一台**电脑上当无线键盘用。


二、第一次使用（配对一个遥控器）
----------------------------------------------------------------
1. 双击 ESP32S3RemoteBridge.exe 打开软件
2. 左侧选「蓝牙配对」
3. 上半部分选串口（选 COM12 那个，它是开发板的 USB 通道；
   COM6 是板载 UART，烧录用）
   点「连接」
4. 点「扫描」

   ★ 遥控器只有「醒着」的时候才会广播 ★
     · Chromecast 遥控器：长按主页键进配对模式
     · 或者按任意键把它唤醒（唤醒后会广播几秒）
     · 小米遥控器同理

5. 列表里出现遥控器名字（Chromecast Remote）后，点它右边的「配对」

   ★ 列表只显示「有名字 + 信号强」的设备（跟 Windows 蓝牙设置一样）★
     没显示出来？点列表下面的「显示所有设备」就能看到全部，
     包括没广播名字的设备（很多手机、IoT 设备本来就不广播名字）。

   ★ 没扫到遥控器？★
     遥控器在睡觉的时候根本不广播。按一下遥控器任意键把它唤醒，
     它会广播几秒 —— 这几秒内点「扫描」就能抓到。
6. 底部的「已配对的遥控器」里出现它 = 配对成功

   配对成功的标志：开发板上的 RGB 灯从「蓝色呼吸」变成「熄灭」
   （呼吸 = 正在找遥控器；熄灭 = 连上了；按下遥控器键 = 亮一下）


三、添加第二台遥控器
----------------------------------------------------------------
重复第二步：点「扫描」-> 唤醒第二台遥控器 -> 点「配对」。
多台遥控器会轮流被连接，互不影响。


四、删除遥控器
----------------------------------------------------------------
「蓝牙配对」页 -> 已配对列表：

· 「删除」      只从列表里移除，**保留配对信息**，随时能再连上
· 「彻底解绑」  真的删掉蓝牙密钥

★ 千万别随手点「彻底解绑」 ★
  它只删我们这边的密钥，遥控器那边还留着旧的配对关系，
  结果它不再接受我们的连接 —— 连不上也配不上，
  只能靠遥控器恢复出厂设置才能救：
    取出电池等 5 分钟 → 按住主页键装回电池 → LED 开始闪就松手。


五、设置按键（平面图 + 学习 + 映射）
----------------------------------------------------------------
左侧选「遥控器设置」：

1. 上传平面图
   点「上传平面图」，选一张遥控器的正面照片（PNG/JPG）。
   没有照片也行 —— 软件自带一张 Chromecast 遥控器的。

2. 标注按键
   点「添加标记」，然后在图上点你想标注的位置 ->
   弹出对话框里填「按键原名」（比如「主页键」「麦克风键」）-> 确定。
   标记可以拖动。

3. 学习按键
   点某个标记 -> 点「学习这个键」-> 按一下遥控器上对应的键 ->
   开发板会把它的 HID 码绑到这个标记上。
   标记会显示成「已绑定」。

4. 映射动作
   下方「按键映射」表格里点某一格 ->
   从分组下拉里选动作（显示桌面 / 鼠标左键单击 / 按住说话 / 启动应用…），
   或者自己写组合键（ctrl+shift+p），也可以点「录制快捷键」直接录。

   每个键有三段：单击 / 双击 / 长按。
   「按住说话」只能配在单击上。


六、语音
----------------------------------------------------------------
左侧选「语音」。

两种用法：
  · 本地识别后直接输入
      电脑本地跑识别模型（已随包），识别出文字后直接粘到你正在输入的窗口里。
  · 交给第三方输入法
      需要装 VB-Cable 之类的虚拟声卡，把音频输出选到它，
      同时让本软件按住输入法的语音热键。

按住遥控器的麦克风键说话，松手结束。


七、固件烧录
----------------------------------------------------------------
左侧选「固件」。
包里已经带了编译好的固件，点「一键刷写随包固件」即可。
（烧录请用板载 CH343 那个口，不是原生 USB 口。）


八、日志（出问题时看这里）
----------------------------------------------------------------
日志在：
  %LOCALAPPDATA%\\ESP32S3RemoteBridge\\logs\\
    app.log     —— 程序自己的日志
    device.log  —— 与开发板的全部协议往来（排障主要看这个）
    flash.log   —— 烧录过程

在「设置」页可以：
  · 点「导出日志 ZIP」生成一份可以直接发给我的包
  · 点「打开日志目录」直接看

★ 排查问题请发 device.log 给我 ★
  里面有协议原文，能完整还原「电脑发了什么、开发板回了什么」。

固件自己的日志在开发板的 UART 上（CH343 口，115200）。


九、开机自启
----------------------------------------------------------------
「设置」页 -> 「随 Windows 启动」开关。
写的是当前用户的注册表 Run 项，不需要管理员权限。
换版本后会自动重新指向新路径。


十、常见问题
----------------------------------------------------------------
Q: 扫不到遥控器？
A: 遥控器在睡觉。按一下遥控器任意键把它唤醒（或者长按主页键
   进配对模式）。Chromecast 遥控器平时根本不广播。

Q: 连上了但按遥控器灯不亮？
A: 看 device.log 里有没有 "已订阅 report id=..."。
   没有的话说明开发板没订阅到按键报告通道。

Q: 配对一直失败？
A: device.log 里搜 "EV PAIR"，里面有 ok=0 和 status。
   status=13 是连接超时 —— 通常还是遥控器没醒。

Q: 之前点过「彻底解绑」，现在连不上了？
A: 这是**预期内**的副作用，说明得说清楚：
   彻底解绑只删开发板这边的密钥，
   但**遥控器那边还留着旧的配对关系**（我们没法远程清掉它）。
   结果就是：它不再接受我们的连接，既连不上也配不上。

   ★ 解法：让遥控器恢复出厂设置，清掉它那边的配对记录 ★
     1. 取出遥控器电池，**等 5 分钟**
     2. 按住主页键，把电池装回去
     3. LED 常亮时继续按住，**灯光开始闪烁时松手**
     4. 然后重新执行上面的配对步骤

   以后点「删除」（不是「彻底解绑」）就不会有这个问题。

Q: 端口找不到？
A: 开发板要插 USB 线。换 USB 口试试。
   原生 USB 口是 COM12，板载 UART 是 COM6。
"""
TEXT


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, help="包目录")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    path = out / "使用说明.txt"
    path.write_text(TEXT, encoding="utf-8")
    print(f"  使用说明 -> {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
